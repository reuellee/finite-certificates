def verify_canonical_two_wall_cycle():
    base = {
        "a": Fraction(1, 2), "b": Fraction(-3), "c": Fraction(-1),
        "d": Fraction(1, 4), "e": Fraction(-1), "f": Fraction(2),
        "g": Fraction(2), "h": Fraction(3), "i": Fraction(-3),
    }
    base_residuals = residual_values(base)
    if [kind for kind, value in base_residuals.items() if not value] != [37, 44]:
        raise AssertionError("the proposed crossing is not exactly the 37/44 double wall")
    base_brackets = [
        column_determinant(standard_columns(base), basis)
        for basis in combinations(range(8), 4)
    ]
    if not all(base_brackets) or min(map(abs, base_brackets)) != Fraction(1, 4):
        raise AssertionError("the 37/44 crossing is not in the uniform parent locus")

    epsilon = Fraction(1, 10000)

    def shifted(x, y):
        values = dict(base)
        values["a"] += x
        values["d"] += y
        return values

    # A is on wall 44 with oriented p_37=-q_37 positive.  The canonical
    # d-pivot into p_44=-q_44>0 reaches B on wall 37.  The canonical a-pivot
    # into p_37>0 reaches C on wall 44.  Thus the wall labels form 44->37->44.
    points = {
        "A": shifted(2 * epsilon, epsilon),
        "B": shifted(2 * epsilon, 3 * epsilon),
        "C": shifted(6 * epsilon, 3 * epsilon),
    }
    expected_pair_values = {
        "A": (Fraction(-1, 2500), Fraction(0)),
        "B": (Fraction(0), Fraction(-3, 1250)),
        "C": (Fraction(-3, 2500), Fraction(0)),
    }
    for name, values in points.items():
        residuals = residual_values(values)
        if (residuals[37], residuals[44]) != expected_pair_values[name]:
            raise AssertionError(f"wrong two-wall values at {name}")
        if any(not residuals[kind] for kind in residuals if kind not in (37, 44)):
            raise AssertionError(f"an unintended residual wall occurs at {name}")
        brackets = [
            column_determinant(standard_columns(values), basis)
            for basis in combinations(range(8), 4)
        ]
        if not all(brackets):
            raise AssertionError(f"point {name} left the uniform parent locus")
        if [value > 0 for value in brackets] != [value > 0 for value in base_brackets]:
            raise AssertionError(f"point {name} left the parent sign cell")

    # On A--B only d changes and on B--C only a changes.  Every parent bracket
    # and every residual representative is affine in that moving coordinate;
    # matching nonzero endpoint signs therefore certify the full open segment.
    for left, right in (("A", "B"), ("B", "C")):
        left_values, right_values = points[left], points[right]
        left_brackets = [
            column_determinant(standard_columns(left_values), basis)
            for basis in combinations(range(8), 4)
        ]
        right_brackets = [
            column_determinant(standard_columns(right_values), basis)
            for basis in combinations(range(8), 4)
        ]
        if any(a * b <= 0 for a, b in zip(left_brackets, right_brackets, strict=True)):
            raise AssertionError(f"a parent wall interrupts segment {left}{right}")
        left_residuals, right_residuals = residual_values(left_values), residual_values(right_values)
        for kind in left_residuals:
            if kind in (37, 44):
                continue
            if left_residuals[kind] * right_residuals[kind] <= 0:
                raise AssertionError(f"residual wall {kind} interrupts segment {left}{right}")

    # Exact transverse derivatives at the double wall.  After orienting both
    # bad sides as p=-q, the canonical positive a-pivot for 37 decreases p_44,
    # while the canonical positive d-pivot for 44 decreases p_37.
    derivatives = {
        "p37_a": Fraction(3),
        "p37_d": Fraction(-2),
        "p44_a": Fraction(-6),
        "p44_d": Fraction(12),
    }
    if derivatives["p37_a"] <= 0 or derivatives["p44_d"] <= 0:
        raise AssertionError("canonical bad directions have wrong signs")
    if derivatives["p44_a"] >= 0 or derivatives["p37_d"] >= 0:
        raise AssertionError("the mutual canonical-pivot obstruction disappeared")
    if derivatives["p37_a"] * derivatives["p44_d"] == derivatives["p37_d"] * derivatives["p44_a"]:
        raise AssertionError("the two residual walls are not transverse")
    return points, derivatives


