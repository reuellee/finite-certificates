#!/usr/bin/env python3
"""Exact verifier for the all-compact first-wall no-go and second-wall count.

This checks three claims from the accompanying note:

1. after including every cofinal padding, the local compact-component matrix
   is the oriented vertex-edge incidence matrix of K_52 and has the primitive
   integral kernel generated by the all-ones vector;
2. the exceptional decoration is realized by an exact rational linear
   semialgebraic cover (not asserted to be a third-compound cover); and
3. every one of the thirteen generic residual four-support types has at least
   thirty strict five-support paddings, each of which forces a further
   residual-wall incidence if its adjacent component is compact.
"""

from fractions import Fraction
from itertools import combinations, permutations


def determinant(matrix):
    """Exact determinant over the rationals, with no optional dependency."""
    if not matrix:
        return Fraction(1)
    size = len(matrix)
    if any(len(row) != size for row in matrix):
        raise ValueError("determinant requires a square matrix")
    work = [[Fraction(value) for value in row] for row in matrix]
    answer = Fraction(1)
    for column in range(size):
        pivot = next(
            (row for row in range(column, size) if work[row][column]),
            None,
        )
        if pivot is None:
            return Fraction(0)
        if pivot != column:
            work[column], work[pivot] = work[pivot], work[column]
            answer = -answer
        pivot_value = work[column][column]
        answer *= pivot_value
        for row in range(column + 1, size):
            if not work[row][column]:
                continue
            scale = work[row][column] / pivot_value
            for other in range(column + 1, size):
                work[row][other] -= scale * work[column][other]
    return answer


def verify_complete_padding_matrix(size=52):
    rows = []
    for left, right in combinations(range(size), 2):
        row = [0] * size
        row[left] = -1
        row[right] = 1
        rows.append(row)

    ones = [1] * size
    if any(sum(a * b for a, b in zip(row, ones, strict=True)) for row in rows):
        raise AssertionError("all-ones vector left the local kernel")

    # The rows (0,j), after deleting column zero, are exactly the identity.
    # Hence they give a unimodular (size-1)-minor.  Row sums zero give the
    # matching upper rank bound, proving kernel Z and no torsion.
    star = [rows[index] for index in range(size - 1)]
    # combinations() orders (0,1),(0,2),...,(0,size-1) first.
    reduced = [row[1:] for row in star]
    identity = [
        [int(row == column) for column in range(size - 1)]
        for row in range(size - 1)
    ]
    if reduced != identity:
        raise AssertionError("star minor is not unimodular identity")
    return len(rows), size - 1


def exact_rank(matrix):
    """Rational row rank for the small linear-model matrices."""
    from fractions import Fraction

    work = [[Fraction(value) for value in row] for row in matrix]
    pivot_row = 0
    if not work:
        return 0
    for column in range(len(work[0])):
        pivot = next(
            (row for row in range(pivot_row, len(work)) if work[row][column]),
            None,
        )
        if pivot is None:
            continue
        work[pivot_row], work[pivot] = work[pivot], work[pivot_row]
        scale = work[pivot_row][column]
        work[pivot_row] = [value / scale for value in work[pivot_row]]
        for row in range(len(work)):
            if row == pivot_row or not work[row][column]:
                continue
            scale = work[row][column]
            work[row] = [
                value - scale * pivot_value
                for value, pivot_value in zip(
                    work[row], work[pivot_row], strict=True
                )
            ]
        pivot_row += 1
        if pivot_row == len(work):
            break
    return pivot_row


def verify_linear_semialgebraic_model():
    # L_0={x3=x4=0}, L_1={x1=x2=0} in R^4.  All 52 padding labels denote
    # L_0 and the partner denotes L_1.  Their intersection is the origin,
    # while every same-signature pair intersection is the noncompact plane
    # L_0.  The equations have integer coefficients.
    l0_equations = ((0, 0, 1, 0), (0, 0, 0, 1))
    l1_equations = ((1, 0, 0, 0), (0, 1, 0, 0))
    if 4 - exact_rank(l0_equations) != 2:
        raise AssertionError("L0 is not a plane")
    if 4 - exact_rank(l1_equations) != 2:
        raise AssertionError("L1 is not a plane")
    if 4 - exact_rank(l0_equations + l1_equations) != 0:
        raise AssertionError("the cross-signature intersection is not a point")

    # Compact-support MV for two closed R^2 pieces meeting in one point has
    # 0 -> Hc^0(point)=Z -> Hc^1(union) -> 0, since Hc^0(R^2)=Hc^1(R^2)=0.
    individual_hc0 = individual_hc1 = 0
    intersection_hc0 = 1
    union_hc1 = intersection_hc0 - individual_hc0 - individual_hc1
    if union_hc1 != 1:
        raise AssertionError("wrong compact-support MV rank in linear model")


