def parse_edge_support(text):
    return tuple(tuple(int(character) for character in edge) for edge in text.split("/"))


def is_structural_four(support):
    if set(support[0]).intersection(*(set(edge) for edge in support[1:])):
        return True
    return any(
        sum(set(pair) <= set(edge) for edge in support) >= 3
        for pair in combinations(range(1, 9), 2)
    )


def is_generic_five(support):
    return all(not is_structural_four(face) for face in combinations(support, 4))


def is_pencil_rigid(first, second):
    support_union = tuple(dict.fromkeys(first + second))
    for label in range(1, 9):
        incident = [set(edge) for edge in support_union if label in edge]
        if len(incident) < 3:
            return False
        if set.intersection(*(edge - {label} for edge in incident)):
            return False
    return True


def verify_all_thirteen_nonlinear_incidence():
    maximum_degrees = {}
    for kind, support_text in RESIDUAL_SUPPORTS.items():
        support = parse_edge_support(support_text)
        label, partner_text = NONLINEAR_INCIDENCE_WITNESSES[kind]
        partner = parse_edge_support(partner_text)
        degree_in_wall = sum(label in edge for edge in support)
        degree_in_partner = sum(label in edge for edge in partner)
        if degree_in_wall < 2 or degree_in_partner != 1:
            raise AssertionError(f"wrong nonlinear incidence witness for type {kind}")
        if not is_generic_five(partner):
            raise AssertionError(f"type {kind} partner is not generic")
        if not is_pencil_rigid(support, partner):
            raise AssertionError(f"type {kind} partner is not pencil-rigid")
        maximum_degrees[kind] = max(
            sum(label in edge for edge in support) for label in range(1, 9)
        )
    expected = {
        36: 3,
        37: 2,
        38: 2,
        39: 3,
        41: 2,
        42: 2,
        44: 2,
        46: 3,
        47: 3,
        48: 2,
        49: 2,
        50: 2,
        51: 2,
    }
    if maximum_degrees != expected:
        raise AssertionError(f"wrong residual support degree table: {maximum_degrees}")
    return maximum_degrees


