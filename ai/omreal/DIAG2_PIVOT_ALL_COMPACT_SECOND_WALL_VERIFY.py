def ellipse_columns(s, t):
    columns = [None] * 8
    for index, column in ELLIPSE_FIXED_COLUMNS.items():
        columns[index] = tuple(Fraction(value) for value in column)
    left = columns[ELLIPSE_PLANE_LABELS[0]]
    right = columns[ELLIPSE_PLANE_LABELS[1]]
    columns[ELLIPSE_MOVING_LABEL] = tuple(
        Fraction(ELLIPSE_AFFINE_ORIGIN[row]) + s * left[row] + t * right[row]
        for row in range(4)
    )
    return tuple(columns)


def column_determinant(columns, indices):
    return determinant(
        [[columns[column][row] for column in indices] for row in range(4)]
    )


def plane_normal(columns, triple):
    three_columns = [columns[column] for column in triple]
    rectangular = [
        [three_columns[column][row] for column in range(3)]
        for row in range(4)
    ]
    return tuple(
        (-1) ** (row + 3)
        * determinant(
            [rectangular[other] for other in range(4) if other != row]
        )
        for row in range(4)
    )


def type_51_derived_determinant(s, t):
    columns = ellipse_columns(s, t)
    support_normals = [plane_normal(columns, edge) for edge in TYPE_51_SUPPORT]
    return determinant(
        [[support_normals[column][row] for column in range(4)] for row in range(4)]
    )


def quadratic_coefficients(function):
    constant = function(Fraction(0), Fraction(0))
    plus_s = function(Fraction(1), Fraction(0))
    minus_s = function(Fraction(-1), Fraction(0))
    plus_t = function(Fraction(0), Fraction(1))
    minus_t = function(Fraction(0), Fraction(-1))
    plus_both = function(Fraction(1), Fraction(1))
    square_s = (plus_s + minus_s - 2 * constant) / 2
    linear_s = (plus_s - minus_s) / 2
    square_t = (plus_t + minus_t - 2 * constant) / 2
    linear_t = (plus_t - minus_t) / 2
    mixed = plus_both - square_s - square_t - linear_s - linear_t - constant
    return square_s, mixed, square_t, linear_s, linear_t, constant


def line_ellipse_discriminant(line, conic):
    """Discriminant after exactly substituting a projective line in a conic."""
    slope_s, slope_t, constant = line
    square_s, mixed, square_t, linear_s, linear_t, conic_constant = conic
    if slope_t:
        qa = square_s * slope_t**2 - mixed * slope_s * slope_t + square_t * slope_s**2
        qb = (
            linear_s * slope_t**2
            - mixed * constant * slope_t
            + 2 * square_t * slope_s * constant
            - linear_t * slope_s * slope_t
        )
        qc = conic_constant * slope_t**2 - linear_t * constant * slope_t + square_t * constant**2
    elif slope_s:
        qa = square_t * slope_s**2
        qb = linear_t * slope_s**2 - mixed * constant * slope_s
        qc = conic_constant * slope_s**2 - linear_s * constant * slope_s + square_s * constant**2
    else:
        return None
    return qb**2 - 4 * qa * qc


def verify_exact_type_51_ellipse():
    conic = quadratic_coefficients(type_51_derived_determinant)
    if conic != tuple(Fraction(value) for value in EXPECTED_ELLIPSE_COEFFICIENTS):
        raise AssertionError(f"wrong exact type-51 conic: {conic}")
    square_s, mixed, square_t, linear_s, linear_t, constant = conic
    quadratic_discriminant = 4 * square_s * square_t - mixed**2
    radius_invariant = (
        square_t * linear_s**2
        - mixed * linear_s * linear_t
        + square_s * linear_t**2
        - constant * quadratic_discriminant
    )
    if square_s <= 0 or quadratic_discriminant <= 0 or radius_invariant <= 0:
        raise AssertionError("the exact type-51 slice is not a nonempty ellipse")

    fixed = tuple(index for index in range(8) if index != ELLIPSE_MOVING_LABEL)
    fixed_brackets = [
        column_determinant(ellipse_columns(Fraction(0), Fraction(0)), basis)
        for basis in combinations(fixed, 4)
    ]
    if not all(fixed_brackets) or min(map(abs, fixed_brackets)) != 96:
        raise AssertionError("the seven fixed parent columns are not uniform")

    hits = set()
    tangencies = set()
    for triple in combinations(fixed, 3):
        def bracket(s, t, triple=triple):
            return column_determinant(
                ellipse_columns(s, t), (ELLIPSE_MOVING_LABEL,) + triple
            )

        constant_line = bracket(Fraction(0), Fraction(0))
        line = (
            bracket(Fraction(1), Fraction(0)) - constant_line,
            bracket(Fraction(0), Fraction(1)) - constant_line,
            constant_line,
        )
        discriminant = line_ellipse_discriminant(line, conic)
        label = "".join(str(index + 1) for index in triple)
        if discriminant is not None and discriminant > 0:
            hits.add(label)
        elif discriminant == 0:
            tangencies.add(label)
    if hits != EXPECTED_ELLIPSE_PARENT_HITS or tangencies:
        raise AssertionError(
            f"wrong exact parent-wall cuts of the ellipse: {hits}, {tangencies}"
        )

    # This partner has label 6 only in 356.  Since y_6(s,t) differs from the
    # affine origin only by y_3,y_5, the normal n_356 is literally constant;
    # the other four partner normals do not involve label 6.  Hence an
    # orientation making this five-circuit positive persists on every
    # uniform arc of the ellipse.
    partner_one_based = parse_edge_support(TYPE_51_PARTNER_SUPPORT_TEXT)
    wall_one_based = tuple(tuple(index + 1 for index in edge) for edge in TYPE_51_SUPPORT)
    if not is_generic_five(partner_one_based) or not is_pencil_rigid(
        wall_one_based, partner_one_based
    ):
        raise AssertionError("the exact ellipse partner is not generic and pencil-rigid")
    partner = tuple(tuple(index - 1 for index in edge) for edge in partner_one_based)
    reference_normals = tuple(
        plane_normal(ellipse_columns(Fraction(0), Fraction(0)), edge)
        for edge in partner
    )
    for s, t in ((1, 0), (0, 1), (7, -3)):
        moved_normals = tuple(
            plane_normal(ellipse_columns(Fraction(s), Fraction(t)), edge)
            for edge in partner
        )
        if moved_normals != reference_normals:
            raise AssertionError("the partner witness does not persist on its plane")
    if exact_rank(tuple(zip(*reference_normals, strict=True))) != 4:
        raise AssertionError("the persistent partner normals do not have rank four")
    partner_cofactors = tuple(
        (-1) ** omitted
        * determinant(
            [
                [reference_normals[column][row] for column in range(5) if column != omitted]
                for row in range(4)
            ]
        )
        for omitted in range(5)
    )
    if not all(partner_cofactors):
        raise AssertionError("the persistent partner dependence is not support-minimal")
    for row in range(4):
        if sum(
            coefficient * reference_normals[column][row]
            for column, coefficient in enumerate(partner_cofactors)
        ):
            raise AssertionError("wrong persistent partner cofactor dependence")
    return quadratic_discriminant, radius_invariant, hits, partner_cofactors


